// Builds the kit's icon font: the Tabler icons listed in icons.mjs, cut down
// from Tabler's 300-weight webfont to just those glyphs, plus their CSS classes
// (`<i class="ti ti-mail"></i>`, as in Tabler's own docs).
//
//   npm run build:icons
//
// Writes src/scss/fonts/icons.woff2, src/scss/fonts/icons.woff,
// src/scss/_icons.scss (the classes) and src/scss/_icon-map.scss (a Sass map
// and mixin for drawing an icon from other rules, e.g. a ::after). Commit them.

import fs from 'node:fs';
import { createRequire } from 'node:module';
import subsetFont from 'subset-font';
import icons from './icons.mjs';

const require = createRequire(import.meta.url);
const tablerDir = require.resolve('@tabler/icons-webfont/package.json').replace(/package\.json$/, '');
const tablerVersion = require('@tabler/icons-webfont/package.json').version;
const root = new URL('../', import.meta.url);

// Tabler's stylesheet maps each icon name to its codepoint: .ti-mail:before { content: "\eae5"; }
const css = fs.readFileSync(`${tablerDir}dist/tabler-icons-300.css`, 'utf8');
const codepoints = {};
for (const [, name, hex] of css.matchAll(/\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"/g)) {
  codepoints[name] = hex;
}

const glyphs = icons.map(name => {
  if (!codepoints[name]) {
    throw new Error(`Tabler has no icon "${name}"; see https://tabler.io/icons`);
  }
  return { name, hex: codepoints[name] };
});

const source = fs.readFileSync(`${tablerDir}dist/fonts/tabler-icons-300.ttf`);
const text = glyphs.map(g => String.fromCodePoint(parseInt(g.hex, 16))).join('');

for (const format of ['woff2', 'woff']) {
  const font = await subsetFont(source, text, { targetFormat: format });
  fs.writeFileSync(new URL(`src/scss/fonts/icons.${format}`, root), font);
  console.log(`src/scss/fonts/icons.${format}: ${(font.length / 1024).toFixed(1)} kB`);
}

const header = `// GENERATED by scripts/build-icons.mjs from scripts/icons.mjs. Don't edit by
// hand; change icons.mjs and run \`npm run build:icons\`.`;

fs.writeFileSync(new URL('src/scss/_icons.scss', root), `${header}
//
// Tabler Icons ${tablerVersion} (MIT, https://tabler.io/icons) at stroke weight
// 300: <i class="ti ti-mail"></i>.

@font-face {
  font-family: $icons-font;
  src: url('fonts/icons.woff2') format('woff2'),
       url('fonts/icons.woff') format('woff');
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.ti {
  display: inline-block;
  font-family: $icons-font !important;
  font-style: normal;
  font-weight: normal;
  line-height: 1;
  vertical-align: -0.125em;
  speak: none;
  text-transform: none;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${glyphs.map(g => `.ti-${g.name}::before { content: "\\${g.hex}"; }`).join('\n')}
`);

fs.writeFileSync(new URL('src/scss/_icon-map.scss', root), `${header}
//
// The kit's icons as a Sass map (Tabler name -> codepoint), for drawing an icon
// from other rules:
//
//   .thing::after { @include icon('check'); }

$icons-font: 'Cranelad Icons' !default;

$icons: (
${glyphs.map(g => `  '${g.name}': "\\${g.hex}",`).join('\n')}
);

@mixin icon($name) {
  @if not map-has-key($icons, $name) {
    @error "Unknown icon '#{$name}'; add it to scripts/icons.mjs.";
  }
  font-family: $icons-font;
  content: map-get($icons, $name);
}
`);

console.log(`src/scss/_icons.scss and _icon-map.scss: ${glyphs.length} icons`);
