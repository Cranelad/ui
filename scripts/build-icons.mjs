// Builds the kit's icon font: the Tabler icons listed in icons.mjs, cut down
// from Tabler's 300-weight webfont to just those glyphs, plus the SCSS that maps
// the Now UI class names (`now-ui-icons ui-1_email-85`) to them.
//
//   npm run build:icons
//
// Writes src/scss/fonts/icons.woff2, src/scss/fonts/icons.woff,
// src/scss/now-ui-kit/_icons.scss (the classes) and
// src/scss/now-ui-kit/_icon-map.scss (a Sass map and mixin for using an icon
// in other rules, e.g. a ::after). Commit all four.

import fs from 'node:fs';
import { createRequire } from 'node:module';
import subsetFont from 'subset-font';
import icons from './icons.mjs';

const require = createRequire(import.meta.url);
const tablerDir = require.resolve('@tabler/icons-webfont/package.json').replace(/package\.json$/, '');
const tablerVersion = require('@tabler/icons-webfont/package.json').version;
const root = new URL('../', import.meta.url);

// Tabler's stylesheet maps each icon name to its codepoint: .ti-mail:before { content: "\eae5"; }
const css = fs.readFileSync(`${tablerDir}dist/tabler-icons-300.css`, 'utf8');
const codepoints = {};
for (const [, name, hex] of css.matchAll(/\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"/g)) {
  codepoints[name] = hex;
}

// Give the font the original (Nucleo) icon font's vertical metrics: ascent of a
// full em, no descent, no line gap. Then an icon's box sits exactly where the
// original's did relative to the text baseline, so layouts don't shift. (Tabler
// uses 90%/10%.) Patches the hhea and OS/2 tables of the TrueType source; the
// subsetter rewrites the font afterwards, recomputing checksums.
function withNucleoMetrics(ttf) {
  const font = Buffer.from(ttf);
  const tables = {};
  const numTables = font.readUInt16BE(4);
  for (let i = 0; i < numTables; i++) {
    const record = 12 + i * 16;
    tables[font.toString('latin1', record, record + 4)] = font.readUInt32BE(record + 8);
  }
  const unitsPerEm = font.readUInt16BE(tables.head + 18);
  const hhea = tables.hhea, os2 = tables['OS/2'];
  font.writeInt16BE(unitsPerEm, hhea + 4); // ascender
  font.writeInt16BE(0, hhea + 6);          // descender
  font.writeInt16BE(0, hhea + 8);          // lineGap
  font.writeInt16BE(unitsPerEm, os2 + 68); // sTypoAscender
  font.writeInt16BE(0, os2 + 70);          // sTypoDescender
  font.writeInt16BE(0, os2 + 72);          // sTypoLineGap
  font.writeUInt16BE(unitsPerEm, os2 + 74); // usWinAscent
  font.writeUInt16BE(0, os2 + 76);          // usWinDescent
  return font;
}

const glyphs = Object.entries(icons).map(([className, tablerName]) => {
  if (!codepoints[tablerName]) {
    throw new Error(`Tabler has no icon "${tablerName}" (for ${className}); see https://tabler.io/icons`);
  }
  return { className, tablerName, hex: codepoints[tablerName] };
});

const source = withNucleoMetrics(fs.readFileSync(`${tablerDir}dist/fonts/tabler-icons-300.ttf`));
const text = [...new Set(glyphs.map(g => String.fromCodePoint(parseInt(g.hex, 16))))].join('');

for (const format of ['woff2', 'woff']) {
  const font = await subsetFont(source, text, { targetFormat: format });
  fs.writeFileSync(new URL(`src/scss/fonts/icons.${format}`, root), font);
  console.log(`src/scss/fonts/icons.${format}: ${(font.length / 1024).toFixed(1)} kB`);
}

const scss = `// GENERATED by scripts/build-icons.mjs from scripts/icons.mjs. Don't edit by
// hand; change icons.mjs and run \`npm run build:icons\`.
//
// The kit's icons: Tabler Icons ${tablerVersion} (MIT, https://tabler.io/icons) at
// stroke weight 300, under the original Now UI Kit class names.
//
// The font has the original icon font's vertical metrics, so each icon's box
// sits where the original's did. Tabler draws inside a 24-unit grid with 2 units
// of padding, centred 0.1em below the middle of that box, so each glyph is
// scaled by 1.2 and lifted by 0.12em (0.1em x 1.2) to fill the box like the
// originals. Both are transforms: visual only, so layouts don't change.

@font-face {
  font-family: $now-ui-icons-font;
  src: url('../fonts/icons.woff2') format('woff2'),
       url('../fonts/icons.woff') format('woff');
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.now-ui-icons {
  display: inline-block;
  font: normal normal normal 14px/1 $now-ui-icons-font;
  font-size: inherit;
  speak: none;
  text-transform: none;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;

  &::before {
    display: inline-block;
    transform: translateY(-0.12em) scale(1.2);
  }
}

// Icon with a round grey background.
.now-ui-icons.circle {
  padding: 0.33333333em;
  vertical-align: -16%;
  background-color: #eee;
  border-radius: 50%;
}

// Lists with icons as bullets: <ul class="nc-icon-ul"><li><i class="now-ui-icons ..."></i>...
.nc-icon-ul {
  padding-left: 0;
  margin-left: 2.14285714em;
  list-style-type: none;

  > li {
    position: relative;
  }

  > li > .now-ui-icons {
    position: absolute;
    left: -1.57142857em;
    top: 0.14285714em;
    text-align: center;
  }

  > li > .now-ui-icons.circle {
    top: -0.19047619em;
    left: -1.9047619em;
  }
}

// Spinning icons (e.g. loader_gear, loader_refresh).
.now-ui-icons.spin {
  animation: nc-icon-spin 2s infinite linear;
}

@keyframes nc-icon-spin {
  0% {
    transform: rotate(0deg);
  }

  100% {
    transform: rotate(360deg);
  }
}

// Glyphs: Now UI class name -> Tabler icon.
${glyphs.map(g => `.now-ui-icons.${g.className}::before { content: "\\${g.hex}"; } // ${g.tablerName}`).join('\n')}
`;

fs.writeFileSync(new URL('src/scss/now-ui-kit/_icons.scss', root), scss);

const map = `// GENERATED by scripts/build-icons.mjs from scripts/icons.mjs. Don't edit by
// hand; change icons.mjs and run \`npm run build:icons\`.
//
// The kit's icons as a Sass map (Now UI class name -> codepoint), for drawing
// an icon from other rules:
//
//   .has-success::after { @include now-ui-icon('ui-1_check'); }

$now-ui-icons-font: 'Now UI Icons' !default;

$now-ui-icons: (
${glyphs.map(g => `  '${g.className}': "\\${g.hex}",`).join('\n')}
);

// Font, glyph, and the same scale and lift as .now-ui-icons (see _icons.scss).
// Sets transform, so use it on an element that isn't otherwise transformed.
@mixin now-ui-icon($name) {
  @if not map-has-key($now-ui-icons, $name) {
    @error "Unknown icon '#{$name}'; see scripts/icons.mjs.";
  }
  font-family: $now-ui-icons-font;
  content: map-get($now-ui-icons, $name);
  transform: translateY(-0.12em) scale(1.2);
}
`;
fs.writeFileSync(new URL('src/scss/now-ui-kit/_icon-map.scss', root), map);
console.log(`src/scss/now-ui-kit/_icons.scss and _icon-map.scss: ${glyphs.length} icons`);
