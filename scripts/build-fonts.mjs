// Copies the kit's web fonts out of their @fontsource packages and writes the
// matching @font-face rules, so the fonts are served with the site rather than
// from Google.
//
//   npm run build:fonts
//
// Writes src/scss/fonts/*.woff2, src/scss/fonts/OFL-*.txt and
// src/scss/_fonts.scss. Commit them all.

import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);

// package, CSS file in it, family name to use, subsets to include
const FONTS = [
  { pkg: '@fontsource-variable/dm-sans', css: 'wght.css', family: 'DM Sans', subsets: ['latin', 'latin-ext'] },
  { pkg: '@fontsource-variable/dm-sans', css: 'wght-italic.css', family: 'DM Sans', subsets: ['latin', 'latin-ext'] },
  { pkg: '@fontsource-variable/outfit', css: 'wght.css', family: 'Outfit', subsets: ['latin', 'latin-ext'] },
  { pkg: '@fontsource/dm-serif-display', css: '400.css', family: 'DM Serif Display', subsets: ['latin', 'latin-ext'] },
];

const faces = [];
const licences = new Map();

for (const font of FONTS) {
  const dir = require.resolve(`${font.pkg}/package.json`).replace(/package\.json$/, '');
  const css = fs.readFileSync(dir + font.css, 'utf8');
  for (const [, comment, body] of css.matchAll(/\/\* ([a-z0-9-]+) \*\/\s*@font-face\s*\{([^}]+)\}/g)) {
    const subset = font.subsets.find(s => comment.includes(`-${s}-`) && !(s === 'latin' && comment.includes('-latin-ext-')));
    if (!subset) continue;
    const prop = name => body.match(new RegExp(`${name}:\\s*([^;]+);`))[1].trim();
    const file = prop('src').match(/url\(\.\/files\/([^)]+)\)/)[1];
    fs.copyFileSync(dir + 'files/' + file, new URL(`src/scss/fonts/${file}`, root));
    faces.push(`/* ${comment} */
@font-face {
  font-family: '${font.family}';
  font-style: ${prop('font-style')};
  font-display: swap;
  font-weight: ${prop('font-weight')};
  src: url('fonts/${file}') format('woff2');
  unicode-range: ${prop('unicode-range')};
}`);
  }
  licences.set(font.family, fs.readFileSync(dir + 'LICENSE', 'utf8'));
}

for (const [family, text] of licences) {
  fs.writeFileSync(new URL(`src/scss/fonts/OFL-${family.replace(/ /g, '')}.txt`, root), text);
}

fs.writeFileSync(new URL('src/scss/_fonts.scss', root), `// GENERATED by scripts/build-fonts.mjs. Don't edit by hand.
//
// The kit's fonts, served with the site: DM Sans (text), Outfit (headings) and
// DM Serif Display (display lines). All SIL Open Font License 1.1; see
// fonts/OFL-*.txt. Each subset is only downloaded when a page uses it.

${faces.join('\n\n')}
`);

console.log(`src/scss/_fonts.scss: ${faces.length} font faces, ${licences.size} licences`);
