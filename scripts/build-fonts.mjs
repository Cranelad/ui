// Copies the kit's web font (Open Sans, variable weight) out of its @fontsource
// package and writes the matching @font-face rules, so the font is served with
// the site rather than from Google.
//
//   npm run build:fonts
//
// Writes src/scss/fonts/open-sans-*.woff2, src/scss/fonts/OFL-OpenSans.txt and
// src/scss/_fonts.scss. Commit them all.

import fs from 'node:fs';

const root = new URL('../', import.meta.url);
const pkg = new URL('node_modules/@fontsource-variable/open-sans/', root);
const fonts = new URL('src/scss/fonts/', root);

// Normal and italic, Latin and Latin Extended (enough for English and the
// Southern African languages the sites use).
const faces = [];
for (const css of ['wght.css', 'wght-italic.css']) {
  const source = fs.readFileSync(new URL(css, pkg), 'utf8');
  for (const [, subset, rule] of source.matchAll(/\/\* open-sans-(latin|latin-ext)-wght-\w+ \*\/\s*(@font-face \{[^}]+\})/g)) {
    const file = rule.match(/files\/([\w-]+\.woff2)/)[1];
    fs.copyFileSync(new URL(`files/${file}`, pkg), new URL(file, fonts));
    faces.push(`// ${subset}\n` + rule
      .replace("'Open Sans Variable'", "'Open Sans'")
      .replace(/url\(\.\/files\/([\w-]+\.woff2)\)/, "url('fonts/$1')"));
  }
}

fs.copyFileSync(new URL('LICENSE', pkg), new URL('OFL-OpenSans.txt', fonts));

const version = JSON.parse(fs.readFileSync(new URL('package.json', pkg), 'utf8')).version;
fs.writeFileSync(new URL('src/scss/_fonts.scss', root), `// GENERATED by scripts/build-fonts.mjs. Don't edit by hand; run \`npm run build:fonts\`.
//
// Open Sans ${version} (SIL Open Font License, src/scss/fonts/OFL-OpenSans.txt),
// variable weight 300-800, normal and italic.

${faces.join('\n\n')}
`);

console.log(`Wrote ${faces.length} @font-face rules.`);
